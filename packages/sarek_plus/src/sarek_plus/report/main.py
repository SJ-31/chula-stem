@define
class InPaths:
    classify_cnv: Path | None
    # purecn_curation: Path  # "*.csv", output of `createCurationFile`
    # # contains purity and ploidy estimation
    # purecn_genes: Path  # "*_genes.csv", output of `callAlterations`
    # purecn_variants: Path  # "*_variants.csv", output of `predictSomatic`
    therapy_data_cache: Path | None  # Path to therapy data cache as generated by
    # databases cli
    ascat_purity: Path | None
    freec_purity: Path | None
    purecn_purity: Path | None
    sigprofiler: Path | None  # Sigprofiler results
    msisensor_pro: Path | None
    cosmic_signatures: Path | None  # Reference file with data on cosmic signatures
    vcf_format_somatic: Path | None
    vcf_format_germline: Path | None
    vep_small_somatic: Path | None  # Small somatic variants annotated by VEP
    vep_sv_somatic: Path | None  # Structural somatic variants annotated by VEP
    vep_small_germline: Path | None
    vep_sv_germline: Path | None
    optitype: Path | None  # Optitype results in TSV format

    def has_germline(self) -> bool:
        return self.vep_small_germline is not None or self.vep_sv_germline is not None

    @classmethod
    def new(cls, spec: dict):
        validated = {}
        for req in (f.name for f in fields(InPaths)):
            if p := spec.get(req):
                if not (path := Path(p)).exists():
                    raise ValueError(f"Path {path} does not exist")
                validated[req] = path
            else:
                validated[req] = None
        return cls(**validated)


def read_purity(paths: InPaths) -> list:
    tmp = {"caller": [], "purity": [], "ploidy": []}
    if paths.ascat_purity:
        df = pl.read_csv(paths.ascat_purity, separator="\t")
        tmp["caller"].append("ascat")
        tmp["purity"].append(df["AberrantCellFraction"][0])
        tmp["ploidy"].append(df["Ploidy"][0])
    if paths.freec_purity:
        df = pl.read_csv(
            paths.freec_purity,
            separator="\t",
            has_header=False,
            new_columns=["var", "val"],
        )
        vals = dict(zip(df["var"], df["val"]))
        tmp["caller"].append("freec")
        tmp["ploidy"].append(vals["Output_Ploidy"])
        purity = vals["Sample_Purity"]
        tmp["purity"].append(purity if purity != 1 else "-")
    if paths.purecn_purity:
        df = pl.read_csv(paths.purecn_purity)
        tmp["caller"].append("purecn")
        tmp["purity"].append(df["Purity"][0])
        tmp["ploidy"].append(df["Ploidy"][0])
    data = pl.DataFrame(tmp)
    if data.is_empty():
        return []
    rows = [
        [row["purity"], row["ploidy"], row["caller"]]
        for row in data.iter_rows(named=True)
    ]
    return [["Purity", "Ploidy", "Caller"]] + rows


@define
class VariantTable:
    vtype: str
    display_name: str
    fmt_fn: Callable
    path: Path | None
    style: dict
    kws: dict = field(factory=dict)
    all: pl.DataFrame | None = field(init=False, default=None)
    relevant: pl.DataFrame | None = field(init=False, default=None)
    nonrelevant: pl.DataFrame | None = field(init=False, default=None)

    def __attrs_post_init__(self):
        """
        Call `fmt_fn` and get three dataframes:
        all, relevant, and non-relevant variants
        """
        if self.has_data:
            self.all, self.relevant, self.nonrelevant = self.fmt_fn(
                self.path, **self.kws
            )

    @property
    def has_data(self) -> bool:
        if self.relevant is None and self.nonrelevant is None:
            return self.path is not None and self.path.exists()
        return not (self.relevant.is_empty() and self.nonrelevant.is_empty())

    def build(
        self,
        spec: dict,
        relevant: bool = False,
        decorator: Callable | None = None,
    ):
        data: pl.DataFrame = self.relevant if relevant else self.nonrelevant
        title = f"Relevant {self.display_name}"
        title_cont = f"Relevant {self.display_name} (Continued)"
        prefix = "rel_" if relevant else "non-rel_"
        if not relevant:
            title = "Non-r" + title.removeprefix("Rel")
            title_cont = "Non-r" + title.removeprefix("Rel")
        ResultsReport.build_table(
            spec,
            table_styles=self.style,
            data=data,
            first=title,
            later=title_cont,
            decorator=decorator,
            filename=f"{prefix}{self.vtype}.pdf",
        )


